import { describe, expect, it } from "vitest";
import { cnpControlDigit, isValidCnp, validateCnp } from "../src/index.js";

// All sample CNPs use birth dates in the 1800s, so they cannot belong to a living person.
const NOW = new Date("2026-10-27T12:00:00Z");

describe("validateCnp", () => {
  it("accepts a valid CNP and decodes it", () => {
    const r = validateCnp("3000101221147", NOW);
    expect(r.valid).toBe(true);
    expect(r.data).toEqual({
      cnp: "3000101221147",
      sex: "M",
      birthDate: "1800-01-01",
      countyCode: "22",
      county: "Iași",
      foreigner: false,
    });
  });

  it("accepts county code 70 (CNPs generated by SIIEASC)", () => {
    const r = validateCnp("4991231700016", NOW);
    expect(r.valid).toBe(true);
    expect(r.data?.birthDate).toBe("1899-12-31");
    expect(r.data?.sex).toBe("F");
    expect(r.data?.countyCode).toBe("70");
  });

  it("ignores spaces and dashes", () => {
    expect(isValidCnp("300 0101 22 114-7", NOW)).toBe(true);
  });

  it("rejects a wrong control digit and says which one is expected", () => {
    const r = validateCnp("3000101221148", NOW);
    expect(r.valid).toBe(false);
    expect(r.error).toContain("așteptat 7");
  });

  it.each([
    ["180010122114", "13 cifre"],
    ["18001012211a4", "13 cifre"],
    ["0800101221144", "nu poate fi 0"],
    ["1800230221144", "dată validă"],
    ["1801301221144", "dată validă"],
    ["1800101991144", "nu există"],
    ["1800101220004", "000"],
  ])("rejects %s (%s)", (cnp, message) => {
    const r = validateCnp(cnp, NOW);
    expect(r.valid).toBe(false);
    expect(r.error).toContain(message);
  });

  it("rejects birth dates in the future", () => {
    const first12 = "527010170001"; // 2027-01-01
    const cnp = first12 + cnpControlDigit(first12);
    const r = validateCnp(cnp, NOW);
    expect(r.valid).toBe(false);
    expect(r.error).toContain("viitor");
  });

  it("handles 29 February only in leap years", () => {
    const leap = "600022970001"; // 2000-02-29
    expect(isValidCnp(leap + cnpControlDigit(leap), NOW)).toBe(true);
    const notLeap = "601022970001"; // 2001-02-29
    expect(isValidCnp(notLeap + cnpControlDigit(notLeap), NOW)).toBe(false);
  });

  it("decodes foreign residents (7/8) and foreigners (9)", () => {
    const resident = "888010140001"; // 7/8: century inferred → 1988
    const r1 = validateCnp(resident + cnpControlDigit(resident), NOW);
    expect(r1.data?.birthDate).toBe("1988-01-01");
    expect(r1.data?.sex).toBe("F");
    expect(r1.data?.foreigner).toBe(true);

    const foreign = "905060740010"; // 9: century inferred → 2005
    const r2 = validateCnp(foreign + cnpControlDigit(foreign), NOW);
    expect(r2.data?.birthDate).toBe("2005-06-07");
    expect(r2.data?.sex).toBeNull();
  });

  it("returns 1 when the remainder is 10", () => {
    // Find any 12-digit prefix whose weighted sum gives remainder 10.
    let found = "";
    for (let n = 1; n < 1000 && !found; n++) {
      const prefix = "180010122" + String(n).padStart(3, "0");
      const key = "279146358279";
      let sum = 0;
      for (let i = 0; i < 12; i++) sum += Number(prefix[i]) * Number(key[i]);
      if (sum % 11 === 10) found = prefix;
    }
    expect(found).not.toBe("");
    expect(cnpControlDigit(found)).toBe(1);
  });
});
